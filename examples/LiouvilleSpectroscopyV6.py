"""
Liouville-space 2D spectroscopy solver, version 6.

V6 additions
------------
1. Configurable initial density matrix::

       system.feed_model(
           H_raw,
           mu_opt,
           interaction_type="dipole",
           initial_density_matrix=rho0,
           density_matrix_basis="site",
       )

   It can also be changed after ``feed_model``::

       system.set_initial_density_matrix(rho0, basis="eigen")
       system.clear_initial_density_matrix()  # restore thermal/default rho

2. UFSS pathway generation and translation::

       pathways = system.configure_standard_2d_pathways_with_ufss(
           arrival_times=[0, 100, 200, 300]
       )

   Existing UFSS DiagramGenerator output can be activated directly::

       pathways = system.set_pathways_from_ufss(
           ufss_diagrams,
           component="rephasing",
       )

   The frequency solver is impulsive and third order. By default, translated
   diagrams must contain three interactions in pulse order (0, 1, 2).

3. Individual pathway spectra::

       pathway_spectra = system.generate_2D_pathways(
           w_list,
           tau2=3,
           k_array=k_array,
       )

4. Selective plotting::

       plotter = SpectroscopyPlotter(w_list)
       plotter.plot_rephasing(spectra, component="real")
       plotter.plot_unrephasing(spectra, component="imag")
       plotter.plot_pathway(pathway_spectra, "R1", component="abs")
       plotter.plot_pathways(pathway_spectra, component="real")

The legacy V5 calls remain available, including ``generate_2D_spectra`` and
``SpectroscopyPlotter.plot_spectrum``.
"""

