    def plot_pathway(
        self,
        pathway_spectra,
        pathway,
        component="real",
        **kwargs,
    ):
        """Plot one R1/R2/... matrix from ``generate_2D_pathways`` output."""
        if isinstance(pathway_spectra, dict):
            if pathway not in pathway_spectra:
                available = ", ".join(pathway_spectra)
                raise KeyError(
                    f"Unknown pathway {pathway!r}. Available: {available}"
                )
            data = pathway_spectra[pathway]
        else:
            data = pathway_spectra
        kwargs.setdefault(
            "title", f"{component.capitalize()} / Pathway {pathway}"
        )
        return self.plot(data, component=component, **kwargs)

    def plot_pathways(
        self,
        pathway_spectra,
        pathways=None,
        component="real",
        levels=60,
        cmap=None,
        ncols=3,
        figsize=None,
        save_path=None,
        show=True,
    ):
        """Plot several individual pathways in a compact grid."""
        if not isinstance(pathway_spectra, dict):
            raise TypeError("pathway_spectra must be a dictionary.")
        if pathways is None:
            pathways = list(pathway_spectra)
        else:
            pathways = list(pathways)
        if not pathways:
            raise ValueError("At least one pathway must be selected.")

        selected_component = self._select_component(
            np.zeros((1, 1)), component
        )[1]
        if cmap is None:
            cmap = "magma" if selected_component == "abs" else "RdBu_r"
        ncols = max(1, int(ncols))
        nrows = math.ceil(len(pathways) / ncols)
        if figsize is None:
            figsize = (5 * ncols, 4.5 * nrows)
        fig, axes = plt.subplots(
            nrows, ncols, figsize=figsize, squeeze=False
        )

        for ax, pathway in zip(axes.flat, pathways):
            if pathway not in pathway_spectra:
                raise KeyError(f"Unknown pathway {pathway!r}.")
            data, _ = self._select_component(
                pathway_spectra[pathway], component
            )
            self._plot_subplot(
                ax,
                self.w_list,
                data,
                levels,
                cmap,
                f"{component.capitalize()} / {pathway}",
                xlabel=r"$\omega_1$",
                ylabel=r"$\omega_3$",
                vmin=0 if selected_component == "abs" else None,
            )
        for ax in axes.flat[len(pathways):]:
            ax.set_visible(False)

        fig.tight_layout()
        if save_path:
            fig.savefig(save_path, dpi=300, bbox_inches="tight")
        if show:
            plt.show()
        return fig, axes

    def plot_spectrum(
        self,
        S3_rephasing,
        S3_nonrephasing,
        levels=60,
        figsize=(12, 14),
        save_path=None,
        show=True,
    ):
        """
        Display the legacy 3x2 real/imaginary/absolute comparison.
        """
        fig, axes = plt.subplots(3, 2, figsize=figsize)
        w = self.w_list

        self._plot_subplot(
            axes[0, 0],
            w,
            np.real(S3_rephasing),
            levels,
            "RdBu_r",
            r"Real / Rephasing",
            ylabel=r"$\omega_3$",
        )
        self._plot_subplot(
            axes[0, 1],
            w,
            np.real(S3_nonrephasing),
            levels,
            "RdBu_r",
            r"Real / Non-rephasing",
        )

        self._plot_subplot(
            axes[1, 0],
            w,
            np.imag(S3_rephasing),
            levels,
            "RdBu_r",
            r"Imaginary / Rephasing",
            ylabel=r"$\omega_3$",
        )
        self._plot_subplot(
            axes[1, 1],
            w,
            np.imag(S3_nonrephasing),
            levels,
            "RdBu_r",
            r"Imaginary / Non-rephasing",
        )

        self._plot_subplot(
            axes[2, 0],
            w,
            np.abs(S3_rephasing),
            levels,
            "magma",
            r"Absolute / Rephasing",
            xlabel=r"$\omega_1$",
            ylabel=r"$\omega_3$",
            vmin=0,
        )
        self._plot_subplot(
            axes[2, 1],
            w,
            np.abs(S3_nonrephasing),
            levels,
            "magma",
            r"Absolute / Non-rephasing",
            xlabel=r"$\omega_1$",
            vmin=0,
        )

        plt.tight_layout()

        if save_path:
            fig.savefig(save_path, dpi=300, bbox_inches="tight")

        if show:
            plt.show()
        return fig, axes

    def _plot_subplot(
        self,
        ax,
        w,
        data,
        levels,
        cmap,
        title,
        xlabel=None,
        ylabel=None,
        vmin=None,
        colorbar=True,
    ):
        """Plot one contour panel."""
        lim = np.max(np.abs(data))
        if not np.isfinite(lim):
            raise ValueError("Spectrum contains non-finite values.")
        if lim == 0:
            lim = np.finfo(float).eps
        if vmin is None:
            vmin, vmax = -lim, lim
        else:
            vmax = lim

        contour = ax.contourf(w, w, data, levels, cmap=cmap, vmin=vmin, vmax=vmax)
        ax.set_title(title)
        if xlabel:
            ax.set_xlabel(xlabel)
        if ylabel:
            ax.set_ylabel(ylabel)
        if colorbar:
            ax.figure.colorbar(contour, ax=ax)
        return contour
